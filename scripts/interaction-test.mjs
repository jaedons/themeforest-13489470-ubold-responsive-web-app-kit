import { chromium, expect } from '@playwright/test';
import { createServer } from './serve.mjs';
import { mkdir } from 'node:fs/promises';
const server = createServer();
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const base = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
await page.route(/https?:\/\/(?!127\.0\.0\.1)/, route => route.abort());
const errors = [];
page.on('pageerror', error => errors.push(error.stack));
try {
  await page.goto(base + '/index.html');
  await expect(page.locator('.topbar')).toHaveCSS('height', '60px');
  await page.locator('.profile[data-bs-toggle="dropdown"]').click();
  await expect(page.locator('.profile').locator('..').locator('.dropdown-menu')).toBeVisible();
  await page.locator('.profile').click();
  await page.locator('.open-left').click();
  await expect(page.locator('#wrapper')).toHaveClass(/enlarged/);
  await page.locator('.open-left').click();
  await expect(page.locator('#wrapper')).not.toHaveClass(/enlarged/);
  console.log('PASS header, dropdown and sidebar');
  await mkdir('test-results', { recursive: true });
  await page.screenshot({ path: 'test-results/desktop.png', fullPage: true });
  console.log('Layout', await page.evaluate(() => ({height: document.documentElement.scrollHeight, width: document.documentElement.scrollWidth})));
  await page.goto(base + '/ui-modals.html');
  await page.locator('[data-bs-target="#myModal"]').click();
  await expect(page.locator('#myModal')).toBeVisible();
  await page.locator('#myModal [data-bs-dismiss="modal"]').first().click();
  await expect(page.locator('#myModal')).toBeHidden();
  console.log('PASS modal open and close');
  await page.goto(base + '/ui-tabs.html');
  const tab = page.locator('[href="#profile-2"][data-bs-toggle="tab"]');
  await tab.click();
  await expect(page.locator('#profile-2')).toBeVisible();
  await expect(page.locator('#home-2')).toBeHidden();
  console.log('PASS tab switching');
  await page.goto(base + '/apps-calendar.html');
  const today = await page.evaluate(() => new Date().toISOString().slice(0, 10));
  await page.evaluate(date => document.getElementById('calendar').uboldCalendar.select({start: date, allDay: true}), today);
  await page.locator('#calendar-event-title').fill('Upgrade acceptance test');
  await page.locator('#event-modal .save-event').click();
  await expect(page.locator('#event-modal')).toBeHidden();
  expect(await page.evaluate(() => document.getElementById('calendar').uboldCalendar.getEvents().length)).toBe(4);
  await page.getByText('Upgrade acceptance test', { exact: true }).click();
  await page.locator('#calendar-event-title').fill('Updated acceptance test');
  await page.locator('#event-modal .save-event').click();
  await expect(page.locator('#event-modal')).toBeHidden();
  await page.getByText('Updated acceptance test', { exact: true }).click();
  await page.locator('#event-modal .delete-event').click();
  await expect(page.locator('#event-modal')).toBeHidden();
  expect(await page.evaluate(() => document.getElementById('calendar').uboldCalendar.getEvents().length)).toBe(3);
  console.log('PASS calendar create, edit and delete');
  await expect(page.locator('.modal-backdrop')).toHaveCount(0);
  await page.screenshot({ path: 'test-results/calendar.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(base + '/index.html');
  await expect(page.locator('body')).toHaveClass(/smallscreen/);
  await page.locator('.open-left').click();
  await expect(page.locator('#wrapper')).not.toHaveClass(/enlarged/);
  await expect(page.locator('.content-page')).toHaveCSS('margin-left', '0px');
  await page.waitForTimeout(450);
  await page.locator('.open-left').click();
  await expect(page.locator('.left.side-menu')).toBeHidden();
  await expect(page.locator('.content-page')).toHaveCSS('margin-left', '0px');
  await page.waitForTimeout(450);
  await page.screenshot({ path: 'test-results/mobile.png', fullPage: true });
  console.log('PASS mobile sidebar');
  expect(errors).toEqual([]);
} finally {
  await browser.close();
  await new Promise(resolve => server.close(resolve));
}
